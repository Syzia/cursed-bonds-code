"""
Scan game/images/char and game/images/side and write game/jjk_sprites.rpy.

Convention: images/char/<key>_<expression>.png and images/side/<key>_<expression>.png.
"neutral" is the default attribute, so `show yuji` == `show yuji neutral`.
Side portraits (`image side yuji ...`) are generated too. They appear beside
the dialogue for the 13 Characters that carry an image= tag in
game/jjk_defs.rpy (mc, yuji, megumi, nobara, maki, panda, toge, gojo, yaga,
ijichi, shoko, utahime, sana; added in phase 1, WP0), whenever that person is
not on screen (config.side_image_only_not_showing). Only those 13 take
expression attributes: a new character needs its images here and an image=
tag there.

Each sprite is wrapped in lit_sprite() (game/lighting.rpy): lit by the scene
it stands in, with a contact shadow under its feet. The feet are measured
here from the neutral pose, and the shadow image is drawn if it's missing.
"""
import os, re, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from pngread import load
from raster import Img

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CHAR = os.path.join(ROOT, "game", "images", "char")
SIDE = os.path.join(ROOT, "game", "images", "side")
OUT = os.path.join(ROOT, "game", "jjk_sprites.rpy")

EXPR = ["neutral", "happy", "serious", "angry", "surprised", "sad"]
pat = re.compile(r"^([a-z0-9]+)_([a-z]+)\.png$")


def scan(d):
    found = {}
    if not os.path.isdir(d):
        return found
    for fn in sorted(os.listdir(d)):
        m = pat.match(fn)
        if not m:
            continue
        key, expr = m.groups()
        if expr in EXPR:
            found.setdefault(key, {})[expr] = fn
    return found


SHADOW = os.path.join(ROOT, "game", "images", "fx", "contact_shadow.png")


def draw_shadow(path, w=256, h=64):
    """A soft dark ellipse, darkest in the middle, fading to nothing at the rim."""
    im = Img(w, h, alpha=True)
    for y in range(h):
        for x in range(w):
            dx, dy = (x + 0.5 - w / 2.0) / (w / 2.0), (y + 0.5 - h / 2.0) / (h / 2.0)
            r2 = dx * dx + dy * dy
            if r2 < 1.0:
                a = (1.0 - r2) ** 1.3
                i = (y * w + x) * 4
                im.buf[i:i + 4] = bytes((18, 16, 24, int(255 * a)))
    os.makedirs(os.path.dirname(path), exist_ok=True)
    im.save(path)


def measure_feet(path):
    """(x centre, sole row, width) of the feet: the lowest opaque row, and the
    spread of the bottom 40 rows above it."""
    im = load(path)
    ch = im.ch
    if ch != 4:
        raise SystemExit("%s has no alpha channel" % path)
    sole = None
    for y in range(im.h - 1, -1, -1):
        if any(im.buf[(y * im.w + x) * 4 + 3] > 128 for x in range(im.w)):
            sole = y
            break
    xs = [x for y in range(max(0, sole - 40), sole + 1) for x in range(im.w)
          if im.buf[(y * im.w + x) * 4 + 3] > 128]
    x0, x1 = min(xs), max(xs)
    return (im.w, im.h), ((x0 + x1) // 2, sole, x1 - x0)


if not os.path.exists(SHADOW):
    draw_shadow(SHADOW)
    print("drew", SHADOW)

# Second outfits: outfit key -> (character, condition for wearing it). The
# character's images switch on the condition, so scenes just `show mc`. Kaito
# wears Yotsuka High's uniform until he settles in at Jujutsu High: Arc One's
# opening and the free-roam start both set that flag, and old saves have it.
OUTFITS = {
    "mcyotsuka": ("mc", "not has_flag('settled_in')"),
}
worn = {}
for outfit, (owner, cond) in sorted(OUTFITS.items()):
    worn.setdefault(owner, []).append((outfit, cond))

chars, sides = scan(CHAR), scan(SIDE)
feet_of = {}


def lit(key, fn):
    if key not in feet_of:
        exprs = chars[key]
        ref = exprs.get("neutral") or exprs[sorted(exprs)[0]]
        feet_of[key] = measure_feet(os.path.join(CHAR, ref))
    size, feet = feet_of[key]
    return 'lit_sprite("images/char/%s", %r, %r)' % (fn, size, feet)


def portrait(key, fn):
    return '"images/side/%s"' % fn


def dressed(key, e, table, one):
    """key's expression e, switched to another outfit where one is worn."""
    parts = ['"%s", %s' % (cond, one(outfit, table[outfit][e]))
             for outfit, cond in worn.get(key, []) if e in table.get(outfit, {})]
    if not parts:
        return one(key, table[key][e])
    return 'ConditionSwitch(%s, "True", %s)' % (", ".join(parts), one(key, table[key][e]))


lines = ["## GENERATED by tools/gen_sprite_defs.py — do not hand-edit. Re-run after adding sprites.", ""]

lines.append("## Sprites: <key> <expression>. `neutral` doubles as the bare name.")
lines.append("## lit_sprite(path, canvas size, feet (x centre, sole row, width)): see lighting.rpy.")
lines.append("## A ConditionSwitch picks a second outfit (OUTFITS in the generator).")
for key in sorted(chars):
    if key in OUTFITS:
        continue
    exprs = chars[key]
    if "neutral" in exprs:
        lines.append('image %s = %s' % (key, dressed(key, "neutral", chars, lit)))
    for e in EXPR:
        if e in exprs:
            lines.append('image %s %s = %s' % (key, e, dressed(key, e, chars, lit)))
    lines.append("")

lines.append("## Side portraits for the textbox. Ren'Py resolves `side <key> <attrs>` from the speaker.")
for key in sorted(sides):
    if key in OUTFITS:
        continue
    exprs = sides[key]
    if "neutral" in exprs:
        lines.append('image side %s = %s' % (key, dressed(key, "neutral", sides, portrait)))
    for e in EXPR:
        if e in exprs:
            lines.append('image side %s %s = %s' % (key, e, dressed(key, e, sides, portrait)))
    lines.append("")

with open(OUT, "w", encoding="utf-8") as f:
    f.write("\n".join(lines) + "\n")

print("wrote", OUT)
print("  sprites:", ", ".join("%s(%d)" % (k, len(v)) for k, v in sorted(chars.items())) or "none yet")
print("  sides  :", ", ".join("%s(%d)" % (k, len(v)) for k, v in sorted(sides.items())) or "none yet")
