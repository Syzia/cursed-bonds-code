"""
Scan game/images/char and game/images/side and write game/jjk_sprites.rpy.

Convention: images/char/<key>_<expression>.png and images/side/<key>_<expression>.png.
"neutral" is the default attribute, so `show yuji` == `show yuji neutral`, and
`image side yuji` follows Character(image="yuji") speakers automatically.
"""
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CHAR = os.path.join(ROOT, "game", "images", "char")
SIDE = os.path.join(ROOT, "game", "images", "side")
OUT = os.path.join(ROOT, "game", "jjk_sprites.rpy")

EXPR = ["neutral", "happy", "serious", "angry", "surprised", "sad"]
pat = re.compile(r"^([a-z0-9]+)_([a-z]+)\.png$")


def scan(d):
    found = {}
    if not os.path.isdir(d):
        return found
    for fn in sorted(os.listdir(d)):
        m = pat.match(fn)
        if not m:
            continue
        key, expr = m.groups()
        if expr in EXPR:
            found.setdefault(key, {})[expr] = fn
    return found


chars, sides = scan(CHAR), scan(SIDE)
lines = ["## GENERATED by tools/gen_sprite_defs.py — do not hand-edit. Re-run after adding sprites.", ""]

lines.append("## Sprites: <key> <expression>. `neutral` doubles as the bare name.")
for key in sorted(chars):
    exprs = chars[key]
    if "neutral" in exprs:
        lines.append('image %s = "images/char/%s"' % (key, exprs["neutral"]))
    for e in EXPR:
        if e in exprs:
            lines.append('image %s %s = "images/char/%s"' % (key, e, exprs[e]))
    lines.append("")

lines.append("## Side portraits for the textbox. Ren'Py resolves `side <key> <attrs>` from the speaker.")
for key in sorted(sides):
    exprs = sides[key]
    if "neutral" in exprs:
        lines.append('image side %s = "images/side/%s"' % (key, exprs["neutral"]))
    for e in EXPR:
        if e in exprs:
            lines.append('image side %s %s = "images/side/%s"' % (key, e, exprs[e]))
    lines.append("")

with open(OUT, "w", encoding="utf-8") as f:
    f.write("\n".join(lines) + "\n")

print("wrote", OUT)
print("  sprites:", ", ".join("%s(%d)" % (k, len(v)) for k, v in sorted(chars.items())) or "none yet")
print("  sides  :", ", ".join("%s(%d)" % (k, len(v)) for k, v in sorted(sides.items())) or "none yet")
